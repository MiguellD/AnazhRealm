const fs = require("fs"); const path = require("path");
const S = __dirname; const f = path.join(S, "lage-block.md");
let Z = fs.readFileSync(f, "utf8").split("\n");
const bullet = (praefix) => { const a = Z.findIndex((z) => z.startsWith(praefix)); if (a < 0) return null; let e = a + 1; while (e < Z.length && !Z[e].startsWith("- ")) e++; return [a, e]; };
let n = bullet("- NACHTRAG "); if (n) Z.splice(n[0], n[1] - n[0]);
const arb = bullet("- LOKALE ARBEITER"); if (!arb) throw new Error("LOKALE ARBEITER fehlt");
Z.splice(arb[0], arb[1] - arb[0], ...fs.readFileSync(path.join(S, "lage-arbeiter-0715.txt"), "utf8").trimEnd().split("\n"));
const kurs = bullet("- KURS"); if (!kurs) throw new Error("KURS fehlt");
Z.splice(kurs[1], 0, ...fs.readFileSync(path.join(S, "lage-neu-0715.txt"), "utf8").trimEnd().split("\n"));
let t = Z.join("\n"); const vor = t;
t = t.replace(/IM ZUG 06:05: nichts\./, "IM ZUG: z706 `w28-klima-kontinent` seit 07:01 (Stempel 06:46:53).");
fs.writeFileSync(f, t); console.log("Zeilen", t.split("\n").length, "Zug-Zeile ersetzt", vor !== t);
